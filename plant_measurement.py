def build_measurement_args(
    rod_length_cm: float,
    rod_hue: int = 0,
    rod_hue_tolerance: int = 12,
    output: Path | None = None,
) -> argparse.Namespace:
    """Build the minimal args namespace process_image() needs.

    Lets non-CLI callers (for example the cloud camera refresh) reuse the
    vision pipeline without going through argparse.
    """

    return argparse.Namespace(
        rod_length_cm=float(rod_length_cm),
        rod_hue=int(rod_hue),
        rod_hue_tolerance=int(rod_hue_tolerance),
        output=RESULT_IMAGE if output is None else Path(output),
    )


def process_image(
    image: np.ndarray,
    args: argparse.Namespace,
    capture_number: int,
    timestamp: str | None = None,
) -> CaptureResult:

    reference = detect_reference_rod(
        image,
        args.rod_hue,
        args.rod_hue_tolerance,
    )

    plant = detect_plant(
        image,
        reference,
    )

    measurements = (
        calculate_measurements(
            plant,
            reference,
            args.rod_length_cm,
        )
    )

    result = draw_results(
        image,
        plant,
        reference,
        measurements,
        capture_number,
    )

    # Save each result separately.
    result_path = (
        BASE_DIR
        / f"plant_result_{capture_number}.jpg"
    )

    if not cv2.imwrite(
        str(result_path),
        result,
    ):
        raise RuntimeError(
            f"Could not save result image: "
            f"{result_path}"
        )

    # Also keep the standard latest result.
    if not cv2.imwrite(
        str(args.output),
        result,
    ):
        raise RuntimeError(
            f"Could not save result image: "
            f"{args.output}"
        )

    (
        cm_per_pixel,
        height_cm,
        width_cm,
    ) = measurements

    if timestamp is None:
        timestamp = datetime.now().isoformat(
            timespec="seconds"
        )

    print(
        f"\nCapture {capture_number}:"
    )

    print(
        f"  Timestamp: {timestamp}"
    )

    print(
        f"  Visible leaf count: "
        f"{plant.leaf_count}"
    )

    print(
        f"  Plant height: "
        f"{plant.height_base_y - plant.height_top_y + 1} pixels = "
        f"{height_cm:.2f} cm"
    )

    print(
        f"  Height points: top y={plant.height_top_y}, "
        f"stem base y={plant.height_base_y}, "
        f"x={plant.height_x}"
    )

    print(
        f"  Stem width: "
        f"{plant.stem_width_pixels} pixels = "
        f"{width_cm:.2f} cm"
    )

    print(
        f"  Reference rod: "
        f"{reference.width} x "
        f"{reference.height} pixels"
    )

    print(
        f"  Scale: "
        f"{cm_per_pixel:.5f} cm/pixel"
    )

    print(
        f"  Segmentation confidence: "
        f"{plant.confidence:.3f}"
    )

    return CaptureResult(
        timestamp=timestamp,
        height_cm=height_cm,
        width_cm=width_cm,
        leaf_count=plant.leaf_count,
        cm_per_pixel=cm_per_pixel,
        confidence=plant.confidence,
    )


