def plant_mask(
    image: np.ndarray,
) -> np.ndarray:
    """Create a green plant mask."""

    hsv = cv2.cvtColor(
        image,
        cv2.COLOR_BGR2HSV,
    )

    mask = cv2.inRange(
        hsv,
        np.array(
            [25, 35, 25],
            dtype=np.uint8,
        ),
        np.array(
            [95, 255, 255],
            dtype=np.uint8,
        ),
    )

    mask = cv2.morphologyEx(
        mask,
        cv2.MORPH_OPEN,
        np.ones(
            (5, 5),
            np.uint8,
        ),
    )

    mask = cv2.morphologyEx(
        mask,
        cv2.MORPH_CLOSE,
        np.ones(
            (25, 25),
            np.uint8,
        ),
    )

    return mask


def remove_reference(
    mask: np.ndarray,
    reference: Rectangle,
) -> np.ndarray:

    cleaned = mask.copy()

    padding = max(
        3,
        min(
            reference.width,
            reference.height,
        ) // 5,
    )

    x0 = max(
        0,
        reference.x - padding,
    )

    y0 = max(
        0,
        reference.y - padding,
    )

    x1 = min(
        mask.shape[1],
        reference.right + padding,
    )

    y1 = min(
        mask.shape[0],
        reference.bottom + padding,
    )

    cleaned[
        y0:y1,
        x0:x1
    ] = 0

    return cleaned


def split_leaf_instances(
    mask: np.ndarray,
) -> tuple[int, np.ndarray]:
    """Split touching leaf blobs with watershed."""

    foreground = (
        mask > 0
    ).astype(np.uint8)

    count, labels, stats, _ = (
        cv2.connectedComponentsWithStats(
            foreground,
            connectivity=8,
        )
    )

    cleaned = np.zeros_like(
        mask
    )

    minimum_area = max(
        40,
        mask.size // 30000,
    )

    for label in range(
        1,
        count,
    ):

        if (
            stats[
                label,
                cv2.CC_STAT_AREA
            ]
            >= minimum_area
        ):

            cleaned[
                labels == label
            ] = 255

    distance = cv2.distanceTransform(
        cleaned,
        cv2.DIST_L2,
        5,
    )

    peak_mask = (
        np.uint8(
            distance
            > max(
                2.0,
                distance.max() * 0.35,
            )
        )
        * 255
    )

    connected_components = cast(
        Any,
        cv2.connectedComponents,
    )

    peak_count, markers = (
        connected_components(
            peak_mask,
            connectivity=8,
        )
    )

    if peak_count <= 2:

        final_count = sum(
            stats[
                label,
                cv2.CC_STAT_AREA
            ]
            >= minimum_area
            for label in range(
                1,
                count,
            )
        )

        return (
            int(final_count),
            cleaned,
        )

    bitwise_not = cast(
        Any,
        cv2.bitwise_not,
    )

    unknown = cv2.bitwise_and(
        cleaned,
        bitwise_not(
            peak_mask
        ),
    )

    markers = markers + 1

    markers[
        unknown > 0
    ] = 0

    watershed_input = cv2.cvtColor(
        cleaned,
        cv2.COLOR_GRAY2BGR,
    )

    markers = cv2.watershed(
        watershed_input,
        markers,
    )

    leaf_count = len(
        {
            int(label)
            for label in np.unique(
                markers
            )
            if label > 1
            and np.count_nonzero(
                markers == label
            ) >= minimum_area
        }
    )

    return (
        leaf_count,
        cleaned,
    )


def isolate_main_plant(
    cleaned_mask: np.ndarray,
) -> np.ndarray:
    """Keep the canopy and a narrow, aligned stem while rejecting grass."""

    count, labels, stats, _ = cv2.connectedComponentsWithStats(
        cleaned_mask,
        connectivity=8,
    )

    if count <= 1:
        return cleaned_mask

    image_height = cleaned_mask.shape[0]
    candidates = [
        label
        for label in range(1, count)
        if stats[label, cv2.CC_STAT_AREA] >= max(
            40,
            cleaned_mask.size // 30000,
        )
        and stats[label, cv2.CC_STAT_TOP] < image_height * 0.8
    ]

    if not candidates:
        return cleaned_mask

    canopy_label = max(
        candidates,
        key=lambda label: (
            stats[label, cv2.CC_STAT_AREA] ** 2
            / max(
                stats[label, cv2.CC_STAT_WIDTH]
                * stats[label, cv2.CC_STAT_HEIGHT],
                1,
            )
        ),
    )

    canopy_x = stats[canopy_label, cv2.CC_STAT_LEFT]
    canopy_y = stats[canopy_label, cv2.CC_STAT_TOP]
    canopy_width = stats[canopy_label, cv2.CC_STAT_WIDTH]
    canopy_height = stats[canopy_label, cv2.CC_STAT_HEIGHT]
    canopy_bottom = canopy_y + canopy_height
    canopy_center = canopy_x + canopy_width / 2

    main_plant_mask = np.zeros_like(cleaned_mask)
    main_plant_mask[labels == canopy_label] = 255

    maximum_stem_gap = max(
        25,
        int(round(image_height * 0.18)),
    )
    stem_half_width = max(
        3,
        int(round(canopy_width * 0.30)),
    )

    for label in candidates:
        if label == canopy_label:
            continue

        x = stats[label, cv2.CC_STAT_LEFT]
        y = stats[label, cv2.CC_STAT_TOP]
        width = stats[label, cv2.CC_STAT_WIDTH]
        height = stats[label, cv2.CC_STAT_HEIGHT]
        center = x + width / 2

        if (
            y >= canopy_bottom
            and y <= canopy_bottom + maximum_stem_gap
            and width <= canopy_width * 0.55
            and height >= width
            and abs(center - canopy_center) <= canopy_width * 0.5
        ):
            component = np.zeros_like(cleaned_mask)
            component[labels == label] = 255
            x0 = max(
                0,
                int(round(canopy_center)) - stem_half_width,
            )
            x1 = min(
                cleaned_mask.shape[1],
                int(round(canopy_center)) + stem_half_width + 1,
            )
            core = np.zeros_like(cleaned_mask)
            core[:, x0:x1] = component[:, x0:x1]
            core = cv2.morphologyEx(
                core,
                cv2.MORPH_OPEN,
                cv2.getStructuringElement(
                    cv2.MORPH_RECT,
                    (3, 15),
                ),
            )
            main_plant_mask = cv2.bitwise_or(
                main_plant_mask,
                core,
            )

    return main_plant_mask


def detect_plant(
    image: np.ndarray,
    reference: Rectangle,
) -> PlantMeasurement:

    mask = remove_reference(
        plant_mask(image),
        reference,
    )

    ys, xs = np.where(
        mask > 0
    )

    if xs.size == 0:
        raise RuntimeError(
            "No green plant pixels were detected. "
            "Use a plain background and check that "
            "the plant is green and well lit."
        )

    leaf_count, cleaned = (
        split_leaf_instances(mask)
    )

    cleaned = isolate_main_plant(
        cleaned
    )

    leaf_count, cleaned = (
        split_leaf_instances(cleaned)
    )

    ys, xs = np.where(
        cleaned > 0
    )

    bounds = Rectangle(
        int(xs.min()),
        int(ys.min()),
        int(
            xs.max()
            - xs.min()
            + 1
        ),
        int(
            ys.max()
            - ys.min()
            + 1
        ),
    )

    plant_area = np.count_nonzero(
        cleaned
    )

    image_area = (
        image.shape[0]
        * image.shape[1]
    )

    confidence = min(
        1.0,
        0.5
        + plant_area
        / max(
            image_area * 0.15,
            1,
        ),
    )

    (
        height_top_y,
        height_base_y,
        height_x,
        stem_width_pixels,
    ) = detect_height_axis(
        image,
        cleaned,
        bounds,
    )

    return PlantMeasurement(
        cleaned,
        bounds,
        leaf_count,
        confidence,
        height_top_y,
        height_base_y,
        height_x,
        stem_width_pixels,
    )


def detect_height_axis(
    image: np.ndarray,
    leaf_mask: np.ndarray,
    leaf_bounds: Rectangle,
) -> tuple[int, int, int, int]:
    """Find the leaf top and a continuous narrow stem/soil base axis."""

    height, width = leaf_mask.shape
    ys, xs = np.where(leaf_mask > 0)
    top_y = int(ys.min())
    canopy_bottom = int(ys.max())
    canopy_center_x = int(round(float(xs.mean())))

    axis_half_width = max(
        8,
        min(
            24,
            leaf_bounds.width // 8,
        ),
    )
    x0 = max(0, canopy_center_x - axis_half_width)
    x1 = min(width, canopy_center_x + axis_half_width + 1)

    hsv = cv2.cvtColor(image, cv2.COLOR_BGR2HSV)
    gray = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)

    # Brown/grey stem pixels are accepted only inside the narrow axis
    # beneath the detected leaves; soil elsewhere is never considered.
    brown_or_gray = (
        (
            (hsv[:, :, 0] <= 25)
            & (hsv[:, :, 1] >= 20)
            & (hsv[:, :, 2] >= 25)
        )
        | (
            (hsv[:, :, 1] <= 85)
            & (hsv[:, :, 2] >= 45)
        )
    )
    local_edges = cv2.Canny(gray, 35, 110)
    local_edges = cv2.dilate(
        local_edges,
        cv2.getStructuringElement(
            cv2.MORPH_RECT,
            (3, 9),
        ),
    ) > 0

    axis_mask = brown_or_gray | local_edges
    axis_mask[:, :x0] = False
    axis_mask[:, x1:] = False

    # Start immediately below the leaf cluster and allow small gaps. This
    # makes the stem axis depend on continuity, not soil color alone.
    start_y = min(
        height - 1,
        canopy_bottom + 1,
    )
    max_gap = max(
        8,
        int(round(height * 0.025)),
    )
    gap = 0
    last_y = start_y

    for y in range(start_y, height):
        row_has_signal = bool(
            np.count_nonzero(axis_mask[y, x0:x1])
        )
        if row_has_signal:
            last_y = y
            gap = 0
        else:
            gap += 1
            if gap > max_gap:
                break

    # Estimate the soil surface from the strongest sustained horizontal
    # appearance change inside the plant's own x-range. This prevents the
    # brown soil below the stem from being treated as more stem.
    x_left = max(
        0,
        leaf_bounds.x,
    )
    x_right = min(
        width,
        leaf_bounds.right,
    )
    row_signal = gray[:, x_left:x_right].mean(axis=1)
    smoothed = np.convolve(
        row_signal,
        np.ones(31, dtype=np.float32) / 31.0,
        mode="same",
    )
    change = np.abs(np.diff(smoothed))
    search_start = min(
        height - 2,
        canopy_bottom + max_gap,
    )
    search_stop = max(
        search_start + 1,
        int(round(height * 0.90)),
    )
    soil_surface_y = search_start + int(
        np.argmax(
            change[search_start:search_stop]
        )
    )

    base_y = min(
        last_y,
        soil_surface_y,
    )

    stem_widths: list[int] = []
    stem_mask = brown_or_gray.astype(np.uint8)
    stem_mask = cv2.morphologyEx(
        stem_mask,
        cv2.MORPH_OPEN,
        cv2.getStructuringElement(
            cv2.MORPH_RECT,
            (3, 7),
        ),
    )

    stem_start = min(
        base_y,
        canopy_bottom + max_gap,
    )
    stem_stop = max(
        stem_start + 1,
        base_y - max_gap,
    )

    for y in range(stem_start, stem_stop):
        row = stem_mask[y, x0:x1] > 0
        center_index = canopy_center_x - x0
        if not row.any() or not row[center_index]:
            continue

        left = center_index
        while left > 0 and row[left - 1]:
            left -= 1

        right = center_index
        while right + 1 < row.size and row[right + 1]:
            right += 1

        stem_widths.append(right - left + 1)

    stem_width_pixels = int(
        round(
            float(
                np.median(stem_widths)
                if stem_widths
                else max(1, axis_half_width * 2)
            )
        )
    )

    return (
        top_y,
        base_y,
        canopy_center_x,
        stem_width_pixels,
    )


# ============================================================
# MEASUREMENTS
# ============================================================

def calculate_measurements(
    plant: PlantMeasurement,
    reference: Rectangle,
    rod_length_cm: float,
) -> tuple[float, float, float]:

    if rod_length_cm <= 0:
        raise ValueError(
            "Rod length must be positive"
        )

    reference_pixels = max(
        reference.width,
        reference.height,
    )

    cm_per_pixel = (
        rod_length_cm
        / reference_pixels
    )

    return (
        cm_per_pixel,
        (
            plant.height_base_y
            - plant.height_top_y
            + 1
        )
        * cm_per_pixel,
        plant.stem_width_pixels
        * cm_per_pixel,
    )


# ============================================================
# RESULT IMAGE
# ============================================================

def draw_results(
    image: np.ndarray,
    plant: PlantMeasurement,
    reference: Rectangle,
    measurements: tuple[
        float,
        float,
        float,
    ],
    capture_number: int,
) -> np.ndarray:

    (
        cm_per_pixel,
        height_cm,
        width_cm,
    ) = measurements

    output = image.copy()

    overlay = output.copy()

    overlay[
        plant.mask > 0
    ] = (
        0,
        210,
        0,
    )

    output = cv2.addWeighted(
        output,
        0.7,
        overlay,
        0.3,
        0,
    )

    def draw_box(
        rectangle: Rectangle,
        colour: tuple[
            int,
            int,
            int,
        ],
        label: str,
    ) -> None:

        cv2.rectangle(
            output,
            (
                rectangle.x,
                rectangle.y,
            ),
            (
                rectangle.right,
                rectangle.bottom,
            ),
            colour,
            3,
        )

        cv2.putText(
            output,
            label,
            (
                rectangle.x,
                max(
                    25,
                    rectangle.y - 8,
                ),
            ),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.7,
            colour,
            2,
            cv2.LINE_AA,
        )

    draw_box(
        plant.bounds,
        (0, 255, 0),
        "plant",
    )

    draw_box(
        reference,
        (255, 0, 0),
        "scale rod",
    )

    cv2.line(
        output,
        (
            plant.height_x,
            plant.height_top_y,
        ),
        (
            plant.height_x,
            plant.height_base_y,
        ),
        (0, 165, 255),
        3,
    )
    cv2.circle(
        output,
        (
            plant.height_x,
            plant.height_top_y,
        ),
        7,
        (0, 255, 255),
        -1,
    )
    cv2.circle(
        output,
        (
            plant.height_x,
            plant.height_base_y,
        ),
        7,
        (0, 0, 255),
        -1,
    )
    cv2.putText(
        output,
        "height top",
        (
            min(
                image.shape[1] - 120,
                plant.height_x + 10,
            ),
            max(
                25,
                plant.height_top_y,
            ),
        ),
        cv2.FONT_HERSHEY_SIMPLEX,
        0.55,
        (0, 255, 255),
        2,
        cv2.LINE_AA,
    )
    cv2.putText(
        output,
        "stem base",
        (
            min(
                image.shape[1] - 110,
                plant.height_x + 10,
            ),
            min(
                image.shape[0] - 10,
                plant.height_base_y,
            ),
        ),
        cv2.FONT_HERSHEY_SIMPLEX,
        0.55,
        (0, 0, 255),
        2,
        cv2.LINE_AA,
    )
    stem_half_width = max(
        1,
        plant.stem_width_pixels // 2,
    )
    stem_width_y = min(
        plant.height_base_y,
        max(
            plant.height_top_y,
            plant.height_base_y
            - max(
                10,
                (plant.height_base_y - plant.height_top_y)
                // 3,
            ),
        ),
    )
    cv2.line(
        output,
        (
            plant.height_x - stem_half_width,
            stem_width_y,
        ),
        (
            plant.height_x + stem_half_width,
            stem_width_y,
        ),
        (255, 0, 255),
        3,
    )
    cv2.putText(
        output,
        "stem width",
        (
            min(
                image.shape[1] - 110,
                plant.height_x + 10,
            ),
            max(
                25,
                stem_width_y - 8,
            ),
        ),
        cv2.FONT_HERSHEY_SIMPLEX,
        0.55,
        (255, 0, 255),
        2,
        cv2.LINE_AA,
    )

    lines = [
        f"Capture: {capture_number}",
        f"Visible leaves: {plant.leaf_count}",
        (
            f"Plant height: "
            f"{plant.height_base_y - plant.height_top_y + 1}px "
            f"({height_cm:.2f} cm)"
        ),
        (
            f"Stem width: "
            f"{plant.stem_width_pixels}px "
            f"({width_cm:.2f} cm)"
        ),
        (
            f"Scale: "
            f"{cm_per_pixel:.5f} cm/pixel"
        ),
        (
            f"Segmentation confidence: "
            f"{plant.confidence:.2f}"
        ),
    ]

    for index, text in enumerate(
        lines
    ):

        origin = (
            10,
            28 + index * 28,
        )

        cv2.putText(
            output,
            text,
            origin,
            cv2.FONT_HERSHEY_SIMPLEX,
            0.65,
            (0, 0, 0),
            4,
        )

        cv2.putText(
            output,
            text,
            origin,
            cv2.FONT_HERSHEY_SIMPLEX,
            0.65,
            (255, 255, 255),
            1,
        )

    return output


