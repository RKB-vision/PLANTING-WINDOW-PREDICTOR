def check_cloudinary_credentials() -> None:
    """Make sure the Cloudinary Admin API credentials exist."""

    if not CLOUDINARY_CLOUD_NAME:
        raise RuntimeError(
            "CLOUDINARY_CLOUD_NAME is not set."
        )

    if not CLOUDINARY_API_KEY:
        raise RuntimeError(
            "CLOUDINARY_API_KEY is not set."
        )

    if not CLOUDINARY_API_SECRET:
        raise RuntimeError(
            "CLOUDINARY_API_SECRET is not set."
        )


def cloudinary_auth_header() -> str:
    """Create HTTP Basic Authentication header."""

    credentials = (
        f"{CLOUDINARY_API_KEY}:{CLOUDINARY_API_SECRET}"
    )

    encoded = base64.b64encode(
        credentials.encode("utf-8")
    ).decode("ascii")

    return f"Basic {encoded}"


def get_cloudinary_images(
    prefix: str | None = None,
) -> list[dict[str, Any]]:
    """
    Get images from Cloudinary whose public ID starts with
    the given prefix (defaults to CLOUDINARY_PREFIX).

    Example:

        Plant01_20261008_082804
        Plant01_20261008_102804
        Plant01_20261008_122804
    """

    check_cloudinary_credentials()

    params = {
        "prefix": prefix or CLOUDINARY_PREFIX,
        "max_results": 500,
    }

    url = (
        f"{CLOUDINARY_API_URL}?"
        f"{urllib.parse.urlencode(params)}"
    )

    request = urllib.request.Request(
        url,
        method="GET",
        headers={
            "Authorization": cloudinary_auth_header(),
            "Accept": "application/json",
        },
    )

    try:
        with urllib.request.urlopen(
            request,
            timeout=30,
        ) as response:

            data = json.loads(
                response.read().decode("utf-8")
            )

    except urllib.error.HTTPError as error:

        body = error.read().decode(
            "utf-8",
            errors="replace",
        )

        raise RuntimeError(
            f"Cloudinary API error "
            f"{error.code}: {body}"
        ) from error

    except (
        urllib.error.URLError,
        TimeoutError,
    ) as error:

        raise RuntimeError(
            f"Could not contact Cloudinary: {error}"
        ) from error

    resources = data.get(
        "resources",
        [],
    )

    return resources


def get_processed_ids() -> set[str]:
    """Load Cloudinary IDs that have already been processed."""

    if not PROCESSED_IDS_FILE.exists():
        return set()

    processed: set[str] = set()

    with PROCESSED_IDS_FILE.open(
        "r",
        encoding="utf-8",
    ) as file:

        for line in file:
            value = line.strip()

            if value:
                processed.add(value)

    return processed


def mark_processed(public_id: str) -> None:
    """Remember that a Cloudinary image has been processed."""

    with PROCESSED_IDS_FILE.open(
        "a",
        encoding="utf-8",
    ) as file:

        file.write(public_id + "\n")


def find_new_cloudinary_images(
    required_count: int,
    prefix: str | None = None,
) -> list[dict[str, Any]]:
    """
    Find new Cloudinary images that have not already been processed.

    The Cloudinary prefix identifies the plant.
    """

    processed_ids = get_processed_ids()

    resources = get_cloudinary_images(prefix=prefix)

    new_images: list[dict[str, Any]] = []

    for resource in resources:

        public_id = resource.get("public_id")

        if not public_id:
            continue

        if public_id in processed_ids:
            continue

        new_images.append(resource)

    # Sort by creation time.
    #
    # This gives us chronological observations even if the
    # Cloudinary API response ordering changes.
    new_images.sort(
        key=lambda item: item.get(
            "created_at",
            "",
        )
    )

    return new_images[:required_count]


def download_cloudinary_image(
    resource: dict[str, Any],
    output_path: Path,
) -> np.ndarray:
    """
    Download a Cloudinary image and decode it with OpenCV.
    """

    secure_url = resource.get("secure_url")

    if not secure_url:
        raise RuntimeError(
            "Cloudinary resource did not contain secure_url."
        )

    print(
        f"Downloading: "
        f"{resource.get('public_id', 'unknown')}"
    )

    try:
        with urllib.request.urlopen(
            secure_url,
            timeout=30,
        ) as response:

            encoded = np.frombuffer(
                response.read(),
                dtype=np.uint8,
            )

    except (
        OSError,
        urllib.error.URLError,
    ) as error:

        raise RuntimeError(
            f"Could not download Cloudinary image: "
            f"{error}"
        ) from error

    image = cv2.imdecode(
        encoded,
        cv2.IMREAD_COLOR,
    )

    if image is None:
        raise RuntimeError(
            "Cloudinary returned data that is "
            "not a valid JPEG/image."
        )

    if not cv2.imwrite(
        str(output_path),
        image,
    ):
        raise RuntimeError(
            f"Could not save {output_path}"
        )

    return image


