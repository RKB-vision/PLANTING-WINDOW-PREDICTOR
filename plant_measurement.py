def plant_mask(image: np.ndarray, reference: Rectangle | None = None) -> np.ndarray:
    """Create a plant mask from lightweight rembg foreground and green pixels."""
    global _REMBG_SESSION
    if _REMBG_SESSION is None:
        _REMBG_SESSION = new_session("u2netp", providers=["CPUExecutionProvider"])
    raw_mask = np.asarray(remove_background(
        image, only_mask=True, session=_REMBG_SESSION
    ))
    if raw_mask.ndim == 3:
        raw_mask = cv2.cvtColor(raw_mask, cv2.COLOR_BGR2GRAY)
    # Low-alpha halos can connect the foreground to blurry background foliage.
    mask = np.where(raw_mask >= 128, 255, 0).astype(np.uint8)
    mask = cv2.morphologyEx(
        mask, cv2.MORPH_CLOSE,
        cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (7, 7)),
    )
    if reference is not None:
        hsv = cv2.cvtColor(image, cv2.COLOR_BGR2HSV)
        rod = cv2.inRange(
            hsv, np.array([0, 80, 40], np.uint8),
            np.array([12, 255, 255], np.uint8),
        ) | cv2.inRange(
            hsv, np.array([168, 80, 40], np.uint8),
            np.array([179, 255, 255], np.uint8),
        )
        rod_roi = np.zeros_like(rod)
        rod_roi[:, max(0, reference.x - 3):min(
            image.shape[1], reference.right + 3
        )] = 255
        rod = cv2.dilate(
            cv2.bitwise_and(rod, rod_roi), np.ones((3, 3), np.uint8)
        )
        mask[rod > 0] = 0
        green = cv2.inRange(
            hsv, np.array([20, 20, 15], np.uint8),
            np.array([105, 255, 255], np.uint8),
        )
        mask = cv2.bitwise_and(mask, green)
        mask = cv2.morphologyEx(
            mask, cv2.MORPH_CLOSE,
            cv2.getStructuringElement(cv2.MORPH_RECT, (3, 15)),
        )
    return mask


def remove_reference(
    mask: np.ndarray,
    reference: Rectangle,
) -> np.ndarray:

    cleaned = mask.copy()

    padding = max(
        3,
        min(
            reference.width,
            reference.height,
        ) // 5,
    )

    x0 = max(
        0,
        reference.x - padding,
    )

    y0 = max(
        0,
        reference.y - padding,
    )

    x1 = min(
        mask.shape[1],
        reference.right + padding,
    )

    y1 = min(
        mask.shape[0],
        reference.bottom + padding,
    )

    cleaned[
        y0:y1,
        x0:x1
    ] = 0

    return cleaned


def split_leaf_instances(
    mask: np.ndarray,
) -> tuple[int, np.ndarray]:
    """Split touching leaf blobs with watershed."""

    foreground = (
        mask > 0
    ).astype(np.uint8)

    count, labels, stats, _ = (
        cv2.connectedComponentsWithStats(
            foreground,
            connectivity=8,
        )
    )

    cleaned = np.zeros_like(
        mask
    )

    minimum_area = max(
        40,
        mask.size // 30000,
    )

    for label in range(
        1,
        count,
    ):

        if (
            stats[
                label,
                cv2.CC_STAT_AREA
            ]
            >= minimum_area
        ):

            cleaned[
                labels == label
            ] = 255

    distance = cv2.distanceTransform(
        cleaned,
        cv2.DIST_L2,
        5,
    )

    peak_mask = (
        np.uint8(
            distance
            > max(
                2.0,
                distance.max() * 0.35,
            )
        )
        * 255
    )

    connected_components = cast(
        Any,
        cv2.connectedComponents,
    )

    peak_count, markers = (
        connected_components(
            peak_mask,
            connectivity=8,
        )
    )

    if peak_count <= 2:

        final_count = sum(
            stats[
                label,
                cv2.CC_STAT_AREA
            ]
            >= minimum_area
            for label in range(
                1,
                count,
            )
        )

        return (
            int(final_count),
            cleaned,
        )

    bitwise_not = cast(
        Any,
        cv2.bitwise_not,
    )

    unknown = cv2.bitwise_and(
        cleaned,
        bitwise_not(
            peak_mask
        ),
    )

    markers = markers + 1

    markers[
        unknown > 0
    ] = 0

    watershed_input = cv2.cvtColor(
        cleaned,
        cv2.COLOR_GRAY2BGR,
    )

    markers = cv2.watershed(
        watershed_input,
        markers,
    )

    leaf_count = len(
        {
            int(label)
            for label in np.unique(
                markers
            )
            if label > 1
            and np.count_nonzero(
                markers == label
            ) >= minimum_area
        }
    )

    return (
        leaf_count,
        cleaned,
    )


def isolate_main_plant(
    cleaned_mask: np.ndarray,
) -> np.ndarray:
    """Keep the canopy and a narrow, aligned stem while rejecting grass."""

    count, labels, stats, _ = cv2.connectedComponentsWithStats(
        cleaned_mask,
        connectivity=8,
    )

    if count <= 1:
        return cleaned_mask

    image_height = cleaned_mask.shape[0]
    candidates = [
        label
        for label in range(1, count)
        if stats[label, cv2.CC_STAT_AREA] >= max(
            40,
            cleaned_mask.size // 30000,
        )
        and stats[label, cv2.CC_STAT_TOP] < image_height * 0.8
    ]

    if not candidates:
        return cleaned_mask

    canopy_label = max(
        candidates,
        key=lambda label: (
            stats[label, cv2.CC_STAT_AREA] ** 2
            / max(
                stats[label, cv2.CC_STAT_WIDTH]
                * stats[label, cv2.CC_STAT_HEIGHT],
                1,
            )
        ),
    )

    canopy_x = stats[canopy_label, cv2.CC_STAT_LEFT]
    canopy_y = stats[canopy_label, cv2.CC_STAT_TOP]
    canopy_width = stats[canopy_label, cv2.CC_STAT_WIDTH]
    canopy_height = stats[canopy_label, cv2.CC_STAT_HEIGHT]
    canopy_bottom = canopy_y + canopy_height
    canopy_center = canopy_x + canopy_width / 2

    main_plant_mask = np.zeros_like(cleaned_mask)
    main_plant_mask[labels == canopy_label] = 255

    maximum_stem_gap = max(
        25,
        int(round(image_height * 0.18)),
    )
    stem_half_width = max(
        3,
        int(round(canopy_width * 0.30)),
    )

    for label in candidates:
        if label == canopy_label:
            continue

        x = stats[label, cv2.CC_STAT_LEFT]
        y = stats[label, cv2.CC_STAT_TOP]
        width = stats[label, cv2.CC_STAT_WIDTH]
        height = stats[label, cv2.CC_STAT_HEIGHT]
        center = x + width / 2

        if (
            y >= canopy_bottom
            and y <= canopy_bottom + maximum_stem_gap
            and width <= canopy_width * 0.55
            and height >= width
            and abs(center - canopy_center) <= canopy_width * 0.5
        ):
            component = np.zeros_like(cleaned_mask)
            component[labels == label] = 255
            x0 = max(
                0,
                int(round(canopy_center)) - stem_half_width,
            )
            x1 = min(
                cleaned_mask.shape[1],
                int(round(canopy_center)) + stem_half_width + 1,
            )
            core = np.zeros_like(cleaned_mask)
            core[:, x0:x1] = component[:, x0:x1]
            core = cv2.morphologyEx(
                core,
                cv2.MORPH_OPEN,
                cv2.getStructuringElement(
                    cv2.MORPH_RECT,
                    (3, 15),
                ),
            )
            main_plant_mask = cv2.bitwise_or(
                main_plant_mask,
                core,
            )

    return main_plant_mask


def detect_plant(
    image: np.ndarray,
    reference: Rectangle,
) -> PlantMeasurement:

    mask = plant_mask(image, reference)

    # Keep the camera's full canopy near the red rod and exclude distant
    # background foliage before contour extraction.
    rod_center_x = reference.x + reference.width // 2
    roi_left = max(0, rod_center_x - 1100)
    roi_right = min(mask.shape[1], rod_center_x + 1101)
    mask[:, :roi_left] = 0
    mask[:, roi_right:] = 0
    mask = cv2.morphologyEx(
        mask, cv2.MORPH_OPEN,
        cv2.getStructuringElement(cv2.MORPH_RECT, (3, 3)),
    )

    ys, xs = np.where(
        mask > 0
    )

    if xs.size == 0:
        raise RuntimeError(
            "No green plant pixels were detected. "
            "Use a plain background and check that "
            "the plant is green and well lit."
        )

    contours, _ = cv2.findContours(
        mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE
    )
    if not contours:
        raise RuntimeError("Plant foreground could not be isolated")

    def contour_score(contour: np.ndarray) -> float:
        area = cv2.contourArea(contour)
        moments = cv2.moments(contour)
        center_x = (moments["m10"] / moments["m00"] if moments["m00"]
                    else rod_center_x)
        return area / (abs(center_x - rod_center_x) + 1.0)

    contour = max(contours, key=contour_score)
    cleaned = np.zeros_like(mask)
    cv2.drawContours(cleaned, [contour], -1, 255, cv2.FILLED)
    leaf_count, _ = split_leaf_instances(cleaned)

    ys, xs = np.where(
        cleaned > 0
    )

    bounds = Rectangle(
        int(xs.min()),
        int(ys.min()),
        int(
            xs.max()
            - xs.min()
            + 1
        ),
        int(
            ys.max()
            - ys.min()
            + 1
        ),
    )

    plant_area = np.count_nonzero(
        cleaned
    )

    image_area = (
        image.shape[0]
        * image.shape[1]
    )

    confidence = min(
        1.0,
        0.5
        + plant_area
        / max(
            image_area * 0.15,
            1,
        ),
    )

    (
        height_top_y,
        height_base_y,
        height_x,
        stem_width_pixels,
    ) = detect_height_axis(
        image,
        cleaned,
        bounds,
    )
    bounds = Rectangle(
        bounds.x, bounds.y, bounds.width,
        max(1, height_base_y - bounds.y + 1),
    )

    return PlantMeasurement(
        cleaned,
        bounds,
        leaf_count,
        confidence,
        height_top_y,
        height_base_y,
        height_x,
        stem_width_pixels,
    )


def detect_height_axis(
    image: np.ndarray,
    leaf_mask: np.ndarray,
    leaf_bounds: Rectangle,
) -> tuple[int, int, int, int]:
    """Find the upper plant landmark and stem base/width in a narrow axis."""
    contours, _ = cv2.findContours(
        leaf_mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE
    )
    if not contours:
        raise RuntimeError("Plant contour is empty")
    points = max(contours, key=cv2.contourArea).reshape(-1, 2)
    top_y = int(points[:, 1].min())
    contour_bottom_y = int(points[:, 1].max())
    box_height = max(1, leaf_bounds.height)

    # The stem center is estimated from mask persistence in its lower region.
    band_top = min(contour_bottom_y, top_y + int(round(box_height * 0.55)))
    band_bottom = max(band_top + 1, top_y + int(round(box_height * 0.85)))
    support = np.count_nonzero(leaf_mask[band_top:band_bottom] > 0, axis=0)
    max_support = int(support.max())
    supported_x = np.flatnonzero(support >= max(1, max_support * 0.8))
    center_x = (int(round(float(np.median(supported_x)))) if supported_x.size
                else int(np.median(points[:, 0])))

    def base_at(x: int) -> int:
        left, right = max(0, x - 15), min(leaf_mask.shape[1], x + 16)
        yy, _ = np.where(leaf_mask[:, left:right] > 0)
        return int(yy.max()) if yy.size else contour_bottom_y

    base_y = base_at(center_x)
    clearance = max(1, int(round(box_height * 0.10)))
    width_y = max(top_y, base_y - clearance)
    kernel_size = max(3, int(round(box_height * 0.015)) | 1)

    def closed_row(y: int) -> np.ndarray:
        return cv2.morphologyEx(
            leaf_mask[y:y + 1], cv2.MORPH_CLOSE,
            cv2.getStructuringElement(cv2.MORPH_RECT, (kernel_size, 1)),
        )[0] > 0

    row = closed_row(width_y)
    pixels = np.flatnonzero(row)
    spans = [span for span in np.split(pixels, np.where(np.diff(pixels) > 1)[0] + 1)
             if span.size]
    if spans:
        nearest = min(spans, key=lambda span: abs(float(span.mean()) - center_x))
        if abs(float(nearest.mean()) - center_x) <= 60:
            center_x = int(round(float(nearest.mean())))
            base_y = base_at(center_x)
            width_y = max(top_y, base_y - clearance)
            row = closed_row(width_y)

    if center_x >= row.size or not row[center_x]:
        return top_y, base_y, center_x, 0
    left = center_x
    while left > 0 and row[left - 1]:
        left -= 1
    right = center_x
    while right + 1 < row.size and row[right + 1]:
        right += 1
    return top_y, base_y, center_x, right - left + 1


