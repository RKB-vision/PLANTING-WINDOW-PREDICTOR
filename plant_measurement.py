# ============================================================
# MAIN
# ============================================================

def main() -> int:

    args = parse_args()

    if args.captures <= 0:
        print(
            "ERROR: --captures must be at least 1",
            file=sys.stderr,
        )
        return 1

    if args.day <= 0:
        print(
            "ERROR: --day must be at least 1",
            file=sys.stderr,
        )
        return 1

    try:

        daily_results: list[
            CaptureResult
        ] = []

        # ----------------------------------------------------
        # OFFLINE MODE
        # ----------------------------------------------------

        if args.image is not None:

            print(
                f"Processing local image: "
                f"{args.image}"
            )

            image = load_local_image(
                args.image
            )

            result = process_image(
                image,
                args,
                capture_number=1,
            )

            daily_results.append(
                result
            )

        # ----------------------------------------------------
        # CLOUDINARY MODE
        # ----------------------------------------------------

        else:

            check_cloudinary_credentials()

            print(
                "\nCloudinary mode"
            )

            print(
                f"Cloudinary prefix: "
                f"{CLOUDINARY_PREFIX}"
            )

            print(
                f"Looking for "
                f"{args.captures} "
                f"new image(s)..."
            )

            while len(
                daily_results
            ) < args.captures:

                remaining = (
                    args.captures
                    - len(daily_results)
                )

                print(
                    f"\nNeed {remaining} "
                    f"more image(s)."
                )

                new_images = (
                    find_new_cloudinary_images(
                        remaining
                    )
                )

                if not new_images:

                    print(
                        "No new Cloudinary "
                        "images found."
                    )

                    print(
                        f"Checking again in "
                        f"{CLOUDINARY_POLL_SECONDS} "
                        f"seconds..."
                    )

                    time.sleep(
                        CLOUDINARY_POLL_SECONDS
                    )

                    continue

                for resource in new_images:

                    if len(
                        daily_results
                    ) >= args.captures:
                        break

                    public_id = resource[
                        "public_id"
                    ]

                    print(
                        "\n--------------------------------"
                    )

                    print(
                        f"Processing Cloudinary image:"
                    )

                    print(
                        f"  {public_id}"
                    )

                    local_path = (
                        BASE_DIR
                        / (
                            f"{public_id}.jpg"
                        )
                    )

                    try:
                        image = download_cloudinary_image(
                            resource,
                            local_path,
                        )

                        capture_number = (
                            len(daily_results) + 1
                        )

                        result = process_image(
                            image,
                            args,
                            capture_number=capture_number,
                        )

                        daily_results.append(
                            result
                        )

                        mark_processed(
                            public_id
                        )

                    except Exception as error:
                        print(
                            f"Failed to process {public_id}: "
                            f"{error}",
                            file=sys.stderr,
                        )
                        continue

        # ----------------------------------------------------
        # RECORD RESULTS
        # ----------------------------------------------------

        if daily_results:
            day_label = f"Day-{args.day:02d}"

            write_daily_record(
                day_label,
                args.plant_id,
                daily_results,
            )

    except Exception as error:
        print(
            f"\nERROR: {error}",
            file=sys.stderr,
        )
        return 1

    return 0


if __name__ == "__main__":
    sys.exit(main())