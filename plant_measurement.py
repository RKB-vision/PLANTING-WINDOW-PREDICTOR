# ============================================================

def draw_results(
    image: np.ndarray,
    plant: PlantMeasurement,
    reference: Rectangle,
    measurements: tuple[
        float,
        float,
        float,
    ],
    capture_number: int,
) -> np.ndarray:

    (
        cm_per_pixel,
        height_cm,
        width_cm,
    ) = measurements

    output = image.copy()

    overlay = output.copy()

    overlay[
        plant.mask > 0
    ] = (
        0,
        210,
        0,
    )

    output = cv2.addWeighted(
        output,
        0.7,
        overlay,
        0.3,
        0,
    )

    def draw_box(
        rectangle: Rectangle,
        colour: tuple[
            int,
            int,
            int,
        ],
        label: str,
    ) -> None:

        cv2.rectangle(
            output,
            (
                rectangle.x,
                rectangle.y,
            ),
            (
                rectangle.right,
                rectangle.bottom,
            ),
            colour,
            3,
        )

        cv2.putText(
            output,
            label,
            (
                rectangle.x,
                max(
                    25,
                    rectangle.y - 8,
                ),
            ),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.7,
            colour,
            2,
            cv2.LINE_AA,
        )

    draw_box(
        plant.bounds,
        (0, 255, 0),
        "plant",
    )

    draw_box(
        reference,
        (255, 0, 0),
        "scale rod",
    )

    cv2.line(
        output,
        (
            plant.height_x,
            plant.height_top_y,
        ),
        (
            plant.height_x,
            plant.height_base_y,
        ),
        (0, 165, 255),
        3,
    )
    cv2.circle(
        output,
        (
            plant.height_x,
            plant.height_top_y,
        ),
        7,
        (0, 255, 255),
        -1,
    )
    cv2.circle(
        output,
        (
            plant.height_x,
            plant.height_base_y,
        ),
        7,
        (0, 0, 255),
        -1,
    )
    cv2.putText(
        output,
        "height top",
        (
            min(
                image.shape[1] - 120,
                plant.height_x + 10,
            ),
            max(
                25,
                plant.height_top_y,
            ),
        ),
        cv2.FONT_HERSHEY_SIMPLEX,
        0.55,
        (0, 255, 255),
        2,
        cv2.LINE_AA,
    )
    cv2.putText(
        output,
        "stem base",
        (
            min(
                image.shape[1] - 110,
                plant.height_x + 10,
            ),
            min(
                image.shape[0] - 10,
                plant.height_base_y,
            ),
        ),
        cv2.FONT_HERSHEY_SIMPLEX,
        0.55,
        (0, 0, 255),
        2,
        cv2.LINE_AA,
    )
    stem_clearance = max(1, int(round(plant.bounds.height * 0.10)))
    stem_width_y = max(
        plant.height_top_y, plant.height_base_y - stem_clearance
    )
    stem_width_left = plant.height_x - (plant.stem_width_pixels - 1) // 2
    stem_width_right = stem_width_left + max(0, plant.stem_width_pixels - 1)
    cv2.line(
        output,
        (
            stem_width_left,
            stem_width_y,
        ),
        (
            stem_width_right,
            stem_width_y,
        ),
        (255, 0, 255),
        3,
    )
    cv2.putText(
        output,
        "stem width",
        (
            min(
                image.shape[1] - 110,
                plant.height_x + 10,
            ),
            max(
                25,
                stem_width_y - 8,
            ),
        ),
        cv2.FONT_HERSHEY_SIMPLEX,
        0.55,
        (255, 0, 255),
        2,
        cv2.LINE_AA,
    )

    lines = [
        f"Capture: {capture_number}",
        f"Visible leaves: {plant.leaf_count}",
        (
            f"Plant height: "
            f"{plant.height_base_y - plant.height_top_y + 1}px "
            f"({height_cm:.2f} cm)"
        ),
        (
            f"Stem width: "
            f"{plant.stem_width_pixels}px "
            f"({width_cm:.2f} cm)"
        ),
        (
            f"Scale: "
            f"{cm_per_pixel:.5f} cm/pixel"
        ),
        (
            f"Segmentation confidence: "
            f"{plant.confidence:.2f}"
        ),
    ]

    for index, text in enumerate(
        lines
    ):

        origin = (
            10,
            28 + index * 28,
        )

        cv2.putText(
            output,
            text,
            origin,
            cv2.FONT_HERSHEY_SIMPLEX,
            0.65,
            (0, 0, 0),
            4,
        )

        cv2.putText(
            output,
            text,
            origin,
            cv2.FONT_HERSHEY_SIMPLEX,
            0.65,
            (255, 255, 255),
            1,
        )

    return output


