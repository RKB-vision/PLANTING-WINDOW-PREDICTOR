def calculate_measurements(
    plant: PlantMeasurement,
    reference: Rectangle,
    rod_length_cm: float,
) -> tuple[float, float, float]:

    if rod_length_cm <= 0:
        raise ValueError(
            "Rod length must be positive"
        )

    reference_pixels = max(
        reference.width,
        reference.height,
    )

    cm_per_pixel = (
        rod_length_cm
        / reference_pixels
    )

    return (
        cm_per_pixel,
        (
            plant.height_base_y
            - plant.height_top_y
            + 1
        )
        * cm_per_pixel,
        plant.stem_width_pixels
        * cm_per_pixel,
    )


