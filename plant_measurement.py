# ============================================================
# MAIN
# ============================================================

def main() -> int:

    args = parse_args()

    # One authoritative rod length: the CLI flag wins when given, otherwise the
    # configured CAMERA_ROD_LENGTH_CM is used. It is validated before any image
    # is processed so a bad calibration can never silently skew a measurement.
    if args.rod_length_cm is None:
        args.rod_length_cm = float(CONFIGURED_ROD_LENGTH_CM)

    if (
        args.rod_length_cm is None
        or args.rod_length_cm <= 0
        or not np.isfinite(args.rod_length_cm)
    ):
        print(
            "ERROR: --rod-length-cm must be a positive number of centimetres",
            file=sys.stderr,
        )
        return 1

    if args.captures <= 0:
        print(
            "ERROR: --captures must be at least 1",
            file=sys.stderr,
        )
        return 1

    if args.day <= 0:
        print(
            "ERROR: --day must be at least 1",
            file=sys.stderr,
        )
        return 1

    try:

        capture_records: list[
            CaptureRecord
        ] = []

        # ----------------------------------------------------
        # OFFLINE MODE
        # ----------------------------------------------------

        if args.image is not None:

            print(
                f"Processing local image: "
                f"{args.image}"
            )

            image = load_local_image(
                args.image
            )

            result = process_image(
                image,
                args,
                capture_number=1,
            )

            capture_records.append(
                capture_record_from_result(result)
            )

        # ----------------------------------------------------
        # CLOUDINARY MODE
        # ----------------------------------------------------

        else:

            check_cloudinary_credentials()

            print(
                "\nCloudinary mode"
            )

            print(
                f"Cloudinary prefix: "
                f"{CLOUDINARY_PREFIX}"
            )

            print(
                f"Looking for "
                f"{args.captures} "
                f"new image(s)..."
            )

            while len(
                capture_records
            ) < args.captures:

                remaining = (
                    args.captures
                    - len(capture_records)
                )

                print(
                    f"\nNeed {remaining} "
                    f"more image(s)."
                )

                new_records = (
                    collect_new_capture_records_once(
                        remaining,
                        args,
                    )
                )

                if not new_records:

                    print(
                        "No new Cloudinary "
                        "images found."
                    )

                    print(
                        f"Checking again in "
                        f"{CLOUDINARY_POLL_SECONDS} "
                        f"seconds..."
                    )

                    time.sleep(
                        CLOUDINARY_POLL_SECONDS
                    )

                    continue

                capture_records.extend(
                    new_records
                )

        # ----------------------------------------------------
        # RECORD RESULTS - one row per plant per calendar date
        # ----------------------------------------------------

        if capture_records:

            day_label = f"Day-{args.day:02d}"

            grouped = group_records_by_date(
                capture_records
            )

            for capture_date, group in sorted(
                grouped.items(),
                key=lambda item: item[0] or "",
            ):

                print(
                    f"\nDaily date: "
                    f"{capture_date or 'unplaceable'}"
                )

                write_daily_record(
                    day_label=day_label,
                    plant_id=args.plant_id,
                    results=[],
                    capture_date=capture_date,
                    records=group,
                    rod_length_cm=args.rod_length_cm,
                )

    except Exception as error:
        print(
            f"\nERROR: {error}",
            file=sys.stderr,
        )
        return 1

    return 0


if __name__ == "__main__":
    sys.exit(main())
