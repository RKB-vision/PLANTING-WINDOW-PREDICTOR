"""Plant measurement batch collector.

The ESP32-CAM uploads images to Cloudinary with IDs such as:

    Plant01_20261008_082804
    Plant01_20261008_102804
    Plant01_20261008_122804

This program automatically finds new Plant01 images in Cloudinary,
downloads them, runs the existing OpenCV measurement pipeline, averages
the successful measurements, and stores one daily record in CSV.

Cloudinary credentials are read from environment variables:

    CLOUDINARY_API_KEY
    CLOUDINARY_API_SECRET

The API secret must stay on the computer and must NOT be placed on
the ESP32-CAM.

Examples
--------

Test with four Cloudinary images:

    python3 plant_measurement.py \
        --rod-length-cm 30 \
        --day 1 \
        --plant-id Plant-01 \
        --captures 4

Test with one Cloudinary image:

    python3 plant_measurement.py \
        --rod-length-cm 30 \
        --day 1 \
        --plant-id Plant-01 \
        --captures 1

Offline single-image test:

    python3 plant_measurement.py \
        --image plant.jpg \
        --rod-length-cm 30 \
        --day 1 \
        --plant-id Plant-01
"""

