# REFERENCE ROD DETECTION
# ============================================================

def detect_reference_rod(
    image: np.ndarray,
    rod_hue: int,
    rod_hue_tolerance: int,
) -> Rectangle:
    """Detect the long, bright, saturated, upright reference rod."""

    hsv = cv2.cvtColor(image, cv2.COLOR_BGR2HSV)

    # Red wraps around the HSV hue scale:
    # red can appear near 0 OR near 179.
    lower_hue = (rod_hue - rod_hue_tolerance) % 180
    upper_hue = (rod_hue + rod_hue_tolerance) % 180

    if lower_hue <= upper_hue:
        mask = cv2.inRange(
            hsv,
            np.array([lower_hue, 80, 40], dtype=np.uint8),
            np.array([upper_hue, 255, 255], dtype=np.uint8),
        )
    else:
        first = cv2.inRange(
            hsv,
            np.array([0, 80, 40], dtype=np.uint8),
            np.array([upper_hue, 255, 255], dtype=np.uint8),
        )

        second = cv2.inRange(
            hsv,
            np.array([lower_hue, 80, 40], dtype=np.uint8),
            np.array([179, 255, 255], dtype=np.uint8),
        )

        mask = cv2.bitwise_or(first, second)

    # Reject dark, muted red pixels before morphology.  They are common
    # in leaves, soil, and shadows, but the reference rod is saturated.
    quality_mask = cv2.inRange(
        hsv,
        np.array([0, 100, 55], dtype=np.uint8),
        np.array([179, 255, 255], dtype=np.uint8),
    )
    mask = cv2.bitwise_and(mask, quality_mask)

    # Scale the kernel with the image.  A vertical opening removes notebook
    # lines, while the close bridges small highlights and shadows on the rod.
    vertical_size = max(
        15,
        int(round(image.shape[0] * 0.025)),
    )
    vertical_kernel = cv2.getStructuringElement(
        cv2.MORPH_RECT,
        (3, vertical_size),
    )

    mask = cv2.morphologyEx(
        mask,
        cv2.MORPH_OPEN,
        vertical_kernel,
    )

    mask = cv2.morphologyEx(
        mask,
        cv2.MORPH_CLOSE,
        vertical_kernel,
    )

    contours, _ = cv2.findContours(
        mask,
        cv2.RETR_EXTERNAL,
        cv2.CHAIN_APPROX_SIMPLE,
    )

    image_area = image.shape[0] * image.shape[1]
    candidates: list[tuple[float, Rectangle]] = []

    for contour in contours:
        x, y, width, height = cv2.boundingRect(contour)
        area = cv2.contourArea(contour)

        aspect = height / max(width, 1)
        box_area = width * height

        # We want a tall, narrow object that spans a substantial part of
        # the frame.  A minimum width avoids selecting isolated red lines.
        if (
            area < image_area * 0.001
            or box_area > image_area * 0.25
            or aspect < 4.0
            or height < image.shape[0] * 0.30
            or width < 4
        ):
            continue

        rectangle = Rectangle(
            x,
            y,
            width,
            height,
        )

        rectangularity = area / max(box_area, 1)
        candidate_mask = np.zeros_like(mask)
        cv2.drawContours(
            candidate_mask,
            [contour],
            -1,
            255,
            thickness=cv2.FILLED,
        )

        # Measure how consistently red pixels occupy the candidate's
        # vertical span.  This rejects short red objects and fragmented
        # notebook marks even when their bounding boxes are tall.
        column_profile = np.count_nonzero(
            candidate_mask[y:y + height, x:x + width],
            axis=1,
        )
        vertical_coverage = float(
            np.count_nonzero(column_profile)
        ) / max(height, 1)

        height_score = height / image.shape[0]
        aspect_score = min(aspect / 12.0, 1.0)

        # Prefer a long, narrow, solid, vertically continuous candidate.
        score = (
            height_score
            * aspect_score
            * rectangularity
            * vertical_coverage
        )

        candidates.append(
            (score, rectangle)
        )

    if not candidates:
        raise RuntimeError(
            "Reference rod was not detected. "
            "Use a bright saturated rod, keep it fully visible, "
            "and check --rod-hue."
        )

    return max(
        candidates,
        key=lambda candidate: candidate[0],
    )[1]

